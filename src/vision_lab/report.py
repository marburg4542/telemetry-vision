# แปลง HTML เป็น PDF ด้วยเบราว์เซอร์ แล้วประทับเลขหน้า
# ======================================================================
def html_to_pdf(html: str, out_pdf: Path) -> None:
    browser = find_browser()
    print(f"ใช้เบราว์เซอร์: {browser}")
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        html_file = tmp / "report.html"
        html_file.write_text(html, encoding="utf-8")
        raw_pdf = tmp / "raw.pdf"
        cmd = [
            browser,
            "--headless",
            "--disable-gpu",
            "--no-sandbox",
            f"--user-data-dir={tmp / 'profile'}",
            "--no-pdf-header-footer",
            f"--print-to-pdf={raw_pdf}",
            html_file.as_uri(),
        ]
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        if not raw_pdf.is_file():
            raise DependencyError(f"เบราว์เซอร์สร้าง PDF ไม่สำเร็จ\n{r.stdout}\n{r.stderr}")
        stamp_page_numbers(raw_pdf, out_pdf)


def stamp_page_numbers(src: Path, dst: Path) -> None:
    """ประทับเลขหน้าด้วย ReportLab (ตัวเลขและอังกฤษล้วน จึงไม่มีปัญหาการจัดวางวรรณยุกต์)"""
    from pypdf import PdfReader, PdfWriter
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfgen import canvas

    reader = PdfReader(str(src))
    writer = PdfWriter()
    total = len(reader.pages)

    for i, page in enumerate(reader.pages, start=1):
        if i > 1:  # ไม่ใส่เลขหน้าบนหน้าปก
            buf = io.BytesIO()
            c = canvas.Canvas(buf, pagesize=A4)
            c.setFont("Helvetica", 8)
            c.setFillColorRGB(0.36, 0.39, 0.47)
            c.drawString(18 * 72 / 25.4, 12 * 72 / 25.4, "YOLOv8 Vehicle Detection Guide")
            c.drawRightString(A4[0] - 18 * 72 / 25.4, 12 * 72 / 25.4, f"{i} / {total}")
            c.save()
            buf.seek(0)
            page.merge_page(PdfReader(buf).pages[0])
        writer.add_page(page)

    dst.parent.mkdir(parents=True, exist_ok=True)
    with dst.open("wb") as f:
        writer.write(f)


def build_report(
    paths: ProjectPaths,
    *,
    output: Path | None = None,
    run_name: str | None = None,
) -> Path:
    """สร้าง PDF อธิบายทฤษฎี โดยดึงภาพประกอบจากโฟลเดอร์ผลการเทรนใน runs/"""
    runs_root = paths.root / "runs"
    run_dir = runs_root / (run_name or DEFAULT_RUN_NAME)
    if not run_dir.is_dir():
        available = ", ".join(sorted(d.name for d in runs_root.glob("*") if d.is_dir()))
        raise DependencyError(
            f"ไม่พบโฟลเดอร์ผลการเทรน: {run_dir}\nที่มีอยู่: {available or 'ไม่มี'}"
        )
    destination = output or paths.output_dir("pdf") / DEFAULT_PDF_NAME
    html_to_pdf(build_html(run_dir), destination)
    return destination
