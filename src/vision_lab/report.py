def h1(t):
    return f'<h1>{t}</h1>'


def h2(t):
    return f'<h2>{t}</h2>'


def h3(t):
    return f'<h3>{t}</h3>'


def p(t):
    return f'<p>{t}</p>'


def ul(items):
    li = "".join(f"<li>{i}</li>" for i in items)
    return f'<ul>{li}</ul>'


def formula(t):
    return f'<div class="formula">{t}</div>'


def note(title, lines, kind="info"):
    body = "".join(f"<p>{line}</p>" for line in lines)
    return f'<div class="note {kind}"><div class="note-title">{title}</div>{body}</div>'


def table(header, rows, widths=None):
    cols = ""
    if widths:
        cols = "<colgroup>" + "".join(f'<col style="width:{w}">' for w in widths) + "</colgroup>"
    th = "".join(f"<th>{c}</th>" for c in header)
    trs = ""
    for r in rows:
        tds = "".join(f"<td>{c}</td>" for c in r)
        trs += f"<tr>{tds}</tr>"
    return f'<table>{cols}<thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table>'


def figure(path, caption, width="100%"):
    """ฝังภาพเป็น base64 เพื่อให้ไฟล์ HTML ทำงานได้โดยไม่ต้องพึ่งพาไฟล์ภายนอก"""
    fp = Path(path)
    if not fp.is_file():
        return f'<p class="missing">[ไม่พบไฟล์ภาพ: {fp.name}]</p>'
    mime = "image/png" if fp.suffix.lower() == ".png" else "image/jpeg"
    b64 = base64.b64encode(fp.read_bytes()).decode("ascii")
    return (f'<figure><img src="data:{mime};base64,{b64}" style="width:{width}">'
            f'<figcaption>{caption}</figcaption></figure>')


def page_break():
    return '<div class="page-break"></div>'


